// ==============================================================================
// RSSMindly — Master Offline Evaluation Runner
// Runs:
// 1. Cosine similarity threshold sweep (0.80 to 0.98) & PNG chart generator
// 2. Deterministic groundedness benchmark (dev set + frozen held-out set, baseline vs current)
// 3. Replay feed latency and cache hit rate benchmark (mocked Gemini + Supabase)
// Outputs unified results to evals/RESULTS.md and exits non-zero if a regression
// floor is breached, so CI fails on metric drops and not only on crashes.
// ==============================================================================

import fs from 'fs';
import path from 'path';
import { runThresholdSweep } from './sweep_threshold.js';
import { runGroundednessEval } from './eval_groundedness.js';
import { runReplayEval } from './eval_replay.js';
import { estimateCost } from './estimate_cost.js';

// Regression floors = values measured when this harness was last reviewed.
// They are guards against silent regressions, NOT quality targets.
export const REGRESSION_FLOORS = {
  groundednessDevAccuracy: 100,      // dev set is tuned; anything less is a regression
  groundednessHeldoutAccuracy: 50,   // frozen held-out set, current code
  groundednessHeldoutRecall: 41.7,
  replayCacheHits: 7                 // deterministic with the simulated embedder at the production threshold
};

const fmtPct = (v) => (v === null || v === undefined ? 'n/a' : `${v}%`);

function setRow(label, r) {
  return `| ${label} | ${r.total} | ${r.tp} | ${r.tn} | ${r.fp} | ${r.fn} | ${fmtPct(r.accuracy)} | ${fmtPct(r.precision)} | ${fmtPct(r.recall)} |`;
}

function errorList(r) {
  const fps = r.falsePositives.map(x => `- **FP [${x.caseId}]** ${x.category}: ${x.notes}. Flagged: ${x.violations.map(v => `\`${v.value}\``).join(', ')}`);
  const fns = r.falseNegatives.map(x => `- **FN [${x.caseId}]** ${x.category}: ${x.notes}`);
  return [...fps, ...fns].join('\n') || '- None';
}

export async function runAllEvals() {
  console.log('###############################################################');
  console.log('#          RSSMINDLY OFFLINE EVALUATION HARNESS               #');
  console.log('###############################################################\n');

  const sweep = runThresholdSweep();
  const g = runGroundednessEval();
  const replay = await runReplayEval();
  const cost = estimateCost();

  const timestamp = new Date().toISOString();
  const pairs = sweep.scoredPairs;
  const dupCount = pairs.filter(p => p.is_duplicate).length;
  const realEventCount = pairs.filter(p => p.based_on_real_event).length;

  const sweepTableRows = sweep.sweepResults.map(r => {
    const notes = [];
    if (r.threshold === sweep.bestThreshold) notes.push('peak F1');
    if (r.threshold === sweep.defaultThreshold) notes.push('production');
    return `| ${r.threshold.toFixed(2)} | ${r.precision.toFixed(1)}% | ${r.recall.toFixed(1)}% | ${r.f1.toFixed(1)}% | ${r.tp} | ${r.fp} | ${r.tn} | ${r.fn} | ${notes.join(', ')} |`;
  }).join('\n');

  const embedderWarning = sweep.embedderKind === 'simulated'
    ? `> [!WARNING]
> **The similarities in this section come from a simulated embedder** (\`evals/lib/semantic_embedder.js\`): hand-written regex rules authored while looking at this same dataset. They say nothing about how the production embedding model scores these pairs. To get real numbers, run \`GOOGLE_GEMINI_API_KEY=... node evals/embed_pairs.js\` once and commit \`evals/data/pair_embeddings.json\`; the sweep then uses those cached vectors offline.`
    : `> [!NOTE]
> Similarities use cached production-model vectors (\`evals/data/pair_embeddings.json\`). Production embeds headline + first 150 body words; this set has headlines only.`;

  const md = `# RSSMindly — Evaluation Results

*Generated by \`npm run eval\` on ${timestamp}. Every number below is printed by a script in \`evals/\`; labels say whether it is measured, simulated, or modelled.*

| Section | What is real | What is not |
|---|---|---|
| 1. Threshold sweep | The sweep logic and the labels | Similarities (${sweep.embedderKind === 'simulated' ? 'simulated embedder' : 'real cached embeddings'}) |
| 2. Groundedness | Production \`evaluateGroundedness\` run on fixed cases | Cases are AI-authored; dev set was used for tuning |
| 3. Replay | Tier 1 latency, cache logic | Tier 2/3 latency (sleep), token counts (constants), hit/miss (simulated embedder) |

Real-API numbers (actual Gemini calls via the BYOK path, real latency and token usage, real embeddings on production fingerprints) are in [\`LIVE_RESULTS.md\`](LIVE_RESULTS.md), produced by \`evals/live_byok_benchmark.js\`. That run needs a key, so it is not part of CI.

---

## 1. Cosine threshold sweep (dedup quality)

${embedderWarning}

Dataset: \`evals/data/pairs.jsonl\`, ${pairs.length} pairs (${dupCount} duplicates, ${pairs.length - dupCount} non-duplicates). **All ${pairs.length} are AI-authored** (\`synthetic: true\`); ${realEventCount} paraphrase a real news event (\`based_on_real_event: true\`), none are copied from a published headline. Awaiting human review.

Embedder: ${sweep.embedderLabel}

| Threshold | Precision | Recall | F1 | TP | FP | TN | FN | Notes |
|---|---|---|---|---|---|---|---|---|
${sweepTableRows}

![Threshold sweep](threshold_sweep.png)

### Verdict on the production threshold (${sweep.defaultThreshold}), computed, not hand-written
${sweep.assessmentLines.map(l => `- ${l}`).join('\n')}

---

## 2. Deterministic groundedness

- **Dev set**: 30 cases in \`evals/eval_groundedness.js\`. \`groundedness.js\` was changed until these passed, so the current score is optimistic by construction.
- **Held-out set**: ${g.heldoutCurrent.total} cases in \`evals/data/groundedness_heldout.json\`, labelled by ground truth before running and frozen. **This is the honest estimate.**
- **Baseline**: \`api/lib/groundedness.js\` before this work (commit a969d44), frozen at \`evals/baseline/groundedness_v0.js\`.
- All cases are AI-authored. "Positive" = hallucinated summary correctly flagged.

| Set / code | Cases | TP | TN | FP | FN | Accuracy | Precision | Recall |
|---|---|---|---|---|---|---|---|---|
${setRow('Dev / baseline', g.devBaseline)}
${setRow('Dev / current (tuned)', g.devCurrent)}
${setRow('Held-out / baseline', g.heldoutBaseline)}
${setRow('**Held-out / current**', g.heldoutCurrent)}

### Dev set errors, baseline code (what the fixes addressed)
${errorList(g.devBaseline)}

### Held-out errors, current code
${errorList(g.heldoutCurrent)}

### Held-out errors, baseline code
${errorList(g.heldoutBaseline)}

---

## 3. Feed replay (mocked Gemini + Supabase)

Replays \`evals/data/feed_fixture.json\` (${replay.totalArticles} AI-authored articles) through the pipeline logic. Hit/miss decisions use the **simulated** embedder.

| Tier | Latency | Status |
|---|---|---|
| Tier 1 extractive | ${replay.avgTier1} ms | **Measured** (production code, Node, one machine) |
| Exact URL hit | ${replay.avgExactHit} ms | In-memory Map, not Supabase; not representative |
| Semantic hit | ${replay.avgSemHit} ms | **Simulated** (\`sleep(${replay.simulatedLatencyMs.semanticHitRpc})\`) |
| Miss (generation) | ${replay.avgMiss} ms | **Simulated** (\`sleep(${replay.simulatedLatencyMs.geminiGeneration})\`) |
| Tier 3 | ${replay.avgTier3} ms | **Simulated** (\`sleep(${replay.simulatedLatencyMs.tier3Generation})\`) |

- Cache hits: **${replay.totalHits}/${replay.totalArticles}** (${replay.cacheHitRate}%): ${replay.semanticHits} semantic, ${replay.exactHits} exact, ${replay.cacheMisses} misses.
- Tier 2 tokens saved: **${replay.tokenEfficiency}%**, *modelled* with fixed constants (${replay.modelledTokens.tier2Generation} generation + ${replay.modelledTokens.embedding} embedding tokens per call): consumed ${replay.tokensConsumed}, saved ${replay.tokensSaved}.

---

## 4. Cost per 1,000 summaries (input side)

Measured from the exact prompt \`buildTier2Prompt\` produces; tokens estimated as chars/4 (rule of thumb, not a tokenizer count). No prices are hard-coded: run \`evals/estimate_cost.js\` with your current prices to get a dollar figure.

| Prompt | Chars | Est. input tokens |
|---|---|---|
| Fixture average (short AI-authored articles) | ${cost.fixtureAvgPromptChars} | ${cost.fixtureAvgInputTokensEst} |
| Upper bound (500-char title, 4,000-char content cap) | ${cost.upperBoundPromptChars} | ${cost.upperBoundInputTokensEst} |

Formula: \`cost_per_1k = 1000 × (1 − hit_rate) × (in_tokens × price_in + out_tokens × price_out) / 1e6\`. Output tokens and the real hit rate are not measured here.

---

## Regression floors (CI)
\`npm run eval\` exits non-zero if any of these drop: ${Object.entries(REGRESSION_FLOORS).map(([k, v]) => `\`${k} >= ${v}\``).join(', ')}.
`;

  const resultsPath = path.resolve('evals/RESULTS.md');
  fs.writeFileSync(resultsPath, md, 'utf8');
  console.log(`\n📄 Results written to: ${resultsPath}`);

  // Regression gate
  const checks = [
    ['groundednessDevAccuracy', g.devCurrent.accuracy],
    ['groundednessHeldoutAccuracy', g.heldoutCurrent.accuracy],
    ['groundednessHeldoutRecall', g.heldoutCurrent.recall],
    ['replayCacheHits', replay.totalHits]
  ];
  const failures = checks.filter(([k, v]) => !(v >= REGRESSION_FLOORS[k]));
  for (const [k, v] of checks) {
    console.log(`${failures.some(f => f[0] === k) ? '❌' : '✅'} ${k}: ${v} (floor ${REGRESSION_FLOORS[k]})`);
  }
  if (failures.length > 0) {
    console.error(`\n${failures.length} regression floor(s) breached.`);
    process.exitCode = 1;
  }
}

if (process.argv[1]?.endsWith('run_all.js')) {
  runAllEvals().catch(err => {
    console.error(err);
    process.exit(1);
  });
}
